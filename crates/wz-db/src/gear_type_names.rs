#[cfg(test)]
mod tests {
    use super::gear_type_string;

    #[test]
    fn labels_and_missing() {
        assert_eq!(gear_type_string("head"), Some("피부"));
        assert_eq!(gear_type_string("head_n"), Some("피부"));
        assert_eq!(gear_type_string("hair"), Some("헤어"));
        assert_eq!(gear_type_string("cap"), Some("모자"));
        // `body`는 원본에서 주석 처리되어 라벨이 없다.
        assert_eq!(gear_type_string("body"), None);
        assert_eq!(gear_type_string("not_a_gear_type"), None);
    }
}
