/// 맵 이미지 로딩 결과 (워커 스레드 → UI 스레드).
/// 맵 툴팁 영역 + String/ToolTipHelp 설명.
#[derive(Debug, Clone, Default)]
pub struct MapTooltipView {
    pub x1: i32,
    pub y1: i32,
    pub x2: i32,
    pub y2: i32,
    pub title: Option<String>,
    pub desc: Option<String>,
}

/// 미니맵 아이콘 egui 텍스처.
#[derive(Default)]
pub struct MinimapIconTextures {
    pub portal: Option<egui::TextureHandle>,
    pub npc: Option<egui::TextureHandle>,
    pub mob: Option<egui::TextureHandle>,
    pub hidden_portal: Option<egui::TextureHandle>,
}

/// 미니맵 아이콘 원본 캔버스.
#[derive(Debug, Clone, Default)]
pub struct MinimapIcons {
    pub portal: Option<(u32, u32, Vec<u8>)>,
    pub npc: Option<(u32, u32, Vec<u8>)>,
    pub mob: Option<(u32, u32, Vec<u8>)>,
    pub hidden_portal: Option<(u32, u32, Vec<u8>)>,
}

pub struct MapImages {
    pub tiles: Vec<(i32, i32, u32, u32, Vec<u8>)>,
    pub objs: Vec<(i32, i32, u32, u32, Vec<u8>)>,
    pub reactors: Vec<crate::reactor::ReactorView>,
    pub backgrounds: Vec<crate::background::BackgroundLayer>,
    pub waters: Vec<crate::water::WaterLayer>,
    pub particles: Vec<crate::particles::MapParticleLayer>,
    pub lifes: Vec<crate::life::LifeView>,
    pub portals: Vec<crate::portal::PortalView>,
    pub illuminants: Vec<crate::illuminant::IlluminantView>,
}

// ── 로딩 메시지 ───────────────────────────────────────────────────────

pub enum LoadMsg {
    Loaded { tree: DirTree },
    Failed(String),
}

// ── 트리 행 ───────────────────────────────────────────────────────────

#[derive(Clone)]
pub struct TreeRow {
    pub depth: usize,
    pub name: String,
    pub kind: String,
    pub path: String,
    pub expandable: bool,
    pub expanded: bool,
}

// ── 앱 상태 ───────────────────────────────────────────────────────────

/// GUI 렌더용 아바타 파트 (로더의 `AvatarPart` + 최종 좌표/z).
#[derive(Clone, Default)]
pub struct AvatarPartData {
    pub slot: String,
    pub width: u32,
    pub height: u32,
    pub rgba: Vec<u8>,
    pub position: (i32, i32),
    pub z_index: i32,
}

/// GUI 펫 한 동작의 프레임.
#[derive(Clone, Default)]
pub struct PetActionData {
    pub frames: Vec<Vec<AvatarPartData>>,
    pub delay_ms: u32,
}

/// GUI 펫 슬롯 애니메이션 상태.
#[derive(Clone, Default)]
pub struct PetAnimationState {
    pub actions: std::collections::BTreeMap<String, PetActionData>,
    pub weights: Vec<(String, i32)>,
    pub gap_min: u32,
    pub gap_max: u32,
    pub action: String,
    pub frame: usize,
    pub last_time: f64,
    pub next_action: f64,
    pub rng: u64,
}

